"""Render a clearly labelled report from real, secret-free public API results."""
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / "reports/cp6/public-smoke.json"
data = json.loads(source.read_text(encoding="utf-8"))
assert data["passed"] and [c["status"] for c in data["checks"]] == [200, 200, 401, 200]
answer = data["checks"][-1]["body"]
assert answer["provider"] == "groq" and answer["usage"]["source"] == "groq_reported"
esc = lambda value: html.escape(str(value))
rows = "".join(
    f"<tr><td>{esc(c['method'])} {esc(c['path'])}</td><td>{'Valid agent key' if c['name'] == 'ask_with_key' else 'No key'}</td>"
    f"<td class='status'>{c['status']}</td><td>{c['expected']}</td><td>{c['latency_ms']:.2f} ms</td><td>PASS</td></tr>"
    for c in data["checks"]
)
page = f"""<!doctype html><html lang="en"><meta charset="utf-8">
<title>CP6 — Live public API test report</title>
<style>
body{{font:17px system-ui,sans-serif;color:#172b42;background:#f2f5f9;margin:0;padding:42px}}
main{{max-width:1120px;margin:auto;background:white;border:1px solid #d6dfeb;border-radius:14px;padding:32px}}
h1{{margin:10px 0 20px;font-size:31px}} .badge{{color:#167443;font-weight:700;letter-spacing:1px}}
p{{line-height:1.6;margin:10px 0}}table{{width:100%;border-collapse:collapse;margin:26px 0}}
th,td{{text-align:left;padding:14px 12px;border-bottom:1px solid #dce4ed}}th{{background:#edf2f8}}
.status{{font-size:24px;color:#167443;font-weight:700}} code{{font-family:ui-monospace,monospace}}
.details{{background:#f5f8fb;border-radius:8px;padding:18px 22px;margin-top:20px}}small{{color:#54647b}}
</style><main>
<div class="badge">4 / 4 CHECKS PASSED</div><h1>CP6 — Live public API test report</h1>
<p><b>Public URL:</b> <code>{esc(data['base_url'])}</code><br>
<b>Measured at:</b> {esc(data['checked_at_utc'])} (UTC)</p>
<table><thead><tr><th>Request</th><th>Authentication</th><th>Actual HTTP</th><th>Expected</th><th>Elapsed</th><th>Result</th></tr></thead><tbody>{rows}</tbody></table>
<div class="details"><b>Successful live Groq response</b>
<p>Provider: <code>{esc(answer['provider'])}</code> · Model: <code>{esc(answer['model'])}</code><br>
Usage: {answer['usage']['input_tokens']} input / {answer['usage']['output_tokens']} output tokens · Source: <code>groq_reported</code><br>
Configured-price cost estimate: ${answer['usage']['cost_usd']:.8f}</p>
<p>{esc(answer['answer'])}</p></div>
<p><small>Rendered evidence report from reports/cp6/public-smoke.json, generated by actual HTTPS requests.
Credentials and request key headers are omitted. This is a test report, not the Railway dashboard.
Cost is an estimate using configured prices, not a billing invoice.</small></p>
</main></html>"""
target = ROOT / "reports/cp6/public-test.html"
target.write_text(page, encoding="utf-8")
print("Rendered reports/cp6/public-test.html from measured JSON")
